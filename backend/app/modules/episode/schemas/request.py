"""
==============================================================================
LIGHTBURGH EMR

Episode Request Schemas

==============================================================================

Defines request payloads used by the Episode API.

Episode numbers are generated by the platform and are therefore
not accepted from clients.

==============================================================================
"""

from uuid import UUID

from pydantic import BaseModel, Field


class CreateEpisodeRequest(BaseModel):
    """
    Request to create an Episode of Care.
    """

    patient_id: UUID = Field(
        ...,
        description="Patient associated with the Episode.",
    )

    title: str = Field(
        ...,
        min_length=1,
        max_length=255,
        description="Human-readable title of the Episode.",
    )

from enum import Enum


class ConsultationDisposition(str, Enum):
    COMPLETE = "COMPLETE"


class CompleteConsultationRequest(BaseModel):
    """
    Complete an outpatient Doctor Consultation.
    """

    encounter_id: UUID = Field(
        ...,
        description="OPEN Doctor Consultation encounter being completed.",
    )

    disposition: ConsultationDisposition = Field(
        ...,
        description="Clinical disposition selected by the doctor.",
    )

class CompleteDoctorReviewRequest(BaseModel):
    """
    Complete an outpatient Doctor Review.
    """

    encounter_id: UUID = Field(
        ...,
        description="OPEN Doctor Review encounter being completed.",
    )


class WardReviewDisposition(str, Enum):
    """
    Clinical disposition selected during a Ward Review.
    """

    CONTINUE_ADMISSION = "CONTINUE_ADMISSION"
    DISCHARGE = "DISCHARGE"
    TRANSFER = "TRANSFER"
    REFERRAL = "REFERRAL"
    OTHER = "OTHER"


class CompleteWardReviewRequest(BaseModel):
    """
    Complete an inpatient Ward Review.
    """

    encounter_id: UUID = Field(
        ...,
        description="OPEN Ward Review encounter being completed.",
    )

    disposition: WardReviewDisposition = Field(
        ...,
        description="Clinical disposition selected by the doctor.",
    )

    details: str | None = Field(
        default=None,
        max_length=5000,
        description="Additional details required for some dispositions.",
    )

