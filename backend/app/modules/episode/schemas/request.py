"""
==============================================================================
LIGHTBURGH EMR

Episode Request Schemas

==============================================================================

Defines request payloads used by the Episode API.

Episode numbers are generated by the platform and are therefore
not accepted from clients.

==============================================================================
"""

from uuid import UUID

from pydantic import BaseModel, Field


class CreateEpisodeRequest(BaseModel):
    """
    Request to create an Episode of Care.
    """

    patient_id: UUID = Field(
        ...,
        description="Patient associated with the Episode.",
    )

    title: str = Field(
        ...,
        min_length=1,
        max_length=255,
        description="Human-readable title of the Episode.",
    )